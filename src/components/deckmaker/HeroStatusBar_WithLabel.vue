  <li :class="{'heroStatus-status':true,'dark':$props.dark,'compact':$props.compact}" :style="getBarIconStyle($props.type as string)">
    <span>{{getTypeText($props.type as string)}}</span>
    <div class="heroStatus-BarBox">
      <span class="heroStatus-BarBox-text">×{{ $props.value?.toFixed(2) }}</span>
      <div class="heroStatus-BarBox-val" ref="bar-val"></div>
    </div>
  </li>
</template>

