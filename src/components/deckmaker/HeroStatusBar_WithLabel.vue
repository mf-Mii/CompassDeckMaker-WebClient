<script lang="ts">
import { defineComponent } from 'vue'
import {getResource} from "@/script/resources.ts";

export default defineComponent({
  name: 'HeroStatusBar_WithLabel',
  props: {
    value: {
      type: Number,
      default: 0.0,
      max: 1.5,
      min: 0.0,
    },
    type: {
      type: String,
      default: 'atk',
      required: true,
      validator(value: string, props): boolean {
        return ['atk', 'def', 'phy'].includes(value)
      }
    },
    dark: {
      type: Boolean,
      default: false,
    },
    compact: {
      type: Boolean,
      default: false,
    },
  },
  methods: {
    // TODO: 要検証(Generated by Copilot)
    setBarWidth(): void {
      const bar = this.$refs['bar-val'] as HTMLElement
      bar.style.width = `${this.$props.value / 1.5 * 100}%`
    },
    getBarIconStyle(type: string): Record<string, string> {
      let url = ''
      switch (type) {
        case 'atk':
          if (this.$props.dark) url = getResource('views.deckmaker.status.attack_white')
          else url = getResource('views.deckmaker.status.attack')
          break
        case 'def':
          if (this.$props.dark) url = getResource('views.deckmaker.status.defense_white')
          else url = getResource('views.deckmaker.status.defense')
          break
        case 'phy':
          if (this.$props.dark) url = getResource('views.deckmaker.status.physical_white')
          else url = getResource('views.deckmaker.status.physical')
          break
      }
      return { '--cpsdm-tmp-heroStatusIcon': `url(${url})` }
    },
    getTypeText(type: string): string {
      switch (type) {
        case 'atk':
          return '攻撃'
        case 'def':
          return '防御'
        case 'phy':
          return '体力'
        default:
          return ''
      }
    },
  },
  mounted() {
    this.setBarWidth()
  },
})
</script>
